#include "minishell.h"

int	ft_is_operator(char c)
{
	return (c == '|' || c == '<' || c == '>' || c == '&');
}

int	ft_is_space(char c)
{
	return (c == ' ' || c == '\t' || c == '\n'
		|| c == '\v' || c == '\f' || c == '\r');
}
